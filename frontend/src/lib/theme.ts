export function applyTheme(theme: Theme, mode: ThemeMode) {
  const c = theme[mode];
  const root = document.documentElement;
  const vars: [string, string][] = [
    ["--bg", c.bg],
    ["--bg-surface", c.bgSurface],
    ["--bg-input", c.bgInput],
    ["--bg-user-msg", c.bgUserMsg],
    ["--bg-active", c.bgActive],
    ["--bg-hover", c.bgHover],
    ["--bg-ask-btn", c.bgAskBtn],
    ["--border", c.border],
    ["--border-input", c.borderInput],
    ["--text-primary", c.textPrimary],
    ["--text-secondary", c.textSecondary],
    ["--text-muted", c.textMuted],
    ["--text-ask-btn", c.textAskBtn],
    ["--text-link", c.textLink],
    ["--pill-bg", c.pillBg],
    ["--pill-border", c.pillBorder],
    ["--pill-text", c.pillText],
    ["--cursor", c.cursor],
    ["--highlight", c.highlight],
  ];
  vars.forEach(([k, v]) => root.style.setProperty(k, v));
  document.body.style.background = c.bg;
}
